#!/usr/bin/env python3
"""Generate clearly-labelled SYNTHETIC data to exercise the pipeline.

READ THIS BEFORE USING THE OUTPUT FOR ANYTHING.

This produces NUMBERS FROM A RANDOM NUMBER GENERATOR. It is not measurement
data. It contains no chemistry, no real samples and no ground truth. Its only
purpose is to let a developer run prepare -> split -> train -> evaluate end to
end and confirm the plumbing works.

Any metric computed from this data describes the random number generator. It
must never appear in a presentation, a report, or the application as evidence
of anything (master spec sections 54, 55).

Every row is tagged ground_truth_source=SYNTHETIC_NOT_REAL and
sample_id=SYNTH-*, so synthetic rows are obvious anywhere they surface.

Usage:
    python scripts/make_synthetic_demo_data.py --samples 40
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from schema import FEATURE_NAMES  # noqa: E402

DEVICES = ["SYNTH-Device-A", "SYNTH-Device-B", "SYNTH-Device-C"]
LIGHTING = ["synthetic_diffuse", "synthetic_warm", "synthetic_dim"]

# Two arbitrary Lab centroids. Chosen only to be separable enough that the
# pipeline produces a non-degenerate model. They correspond to nothing.
CENTROIDS = {
    "NEGATIVE": {"lab": (78.0, 2.0, 6.0), "hue": 60.0, "sat": 0.12},
    "POSITIVE": {"lab": (32.0, 18.0, -42.0), "hue": 260.0, "sat": 0.62},
}


def synthesise(rng: np.random.Generator, label: str, sample_id: str,
               frame_index: int) -> dict:
    spec = CENTROIDS[label]
    l, a, b = spec["lab"]
    jitter = rng.normal(0, 3.0)

    lab_l = l + rng.normal(0, 4.0)
    lab_a = a + rng.normal(0, 3.0)
    lab_b = b + rng.normal(0, 3.0)

    mean_r = float(np.clip(128 + lab_a * 1.6 + jitter, 0, 255))
    mean_g = float(np.clip(lab_l * 2.2 + rng.normal(0, 6), 0, 255))
    mean_b = float(np.clip(128 - lab_b * 1.4 + jitter, 0, 255))

    return {
        "sample_id": sample_id,
        "session_id": f"{sample_id}-S1",
        "kit_id": "DS-DEMO-001",
        "kit_profile_version": "1.0.0",
        "device_model": DEVICES[hash(sample_id) % len(DEVICES)],
        "lighting_condition": LIGHTING[frame_index % len(LIGHTING)],
        "captured_at_utc": "2026-01-01T00:00:00Z",
        "label": label,
        "ground_truth_source": "SYNTHETIC_NOT_REAL",
        "quality_label": "good",
        "provenance_note": (
            "SYNTHETIC DATA generated by make_synthetic_demo_data.py. Not a "
            "measurement. Not evidence of anything."
        ),
        "mean_r": mean_r,
        "mean_g": mean_g,
        "mean_b": mean_b,
        "median_r": mean_r + rng.normal(0, 2),
        "median_g": mean_g + rng.normal(0, 2),
        "median_b": mean_b + rng.normal(0, 2),
        "std_r": abs(rng.normal(6, 2)),
        "std_g": abs(rng.normal(6, 2)),
        "std_b": abs(rng.normal(6, 2)),
        "hue_circular_mean": float(
            (spec["hue"] + rng.normal(0, 8)) % 360
        ),
        "hue_std": abs(rng.normal(9, 3)),
        "saturation_mean": float(
            np.clip(spec["sat"] + rng.normal(0, 0.05), 0, 1)
        ),
        "value_mean": float(np.clip(lab_l / 100 + rng.normal(0, 0.05), 0, 1)),
        "lab_l": lab_l,
        "lab_a": lab_a,
        "lab_b": lab_b,
        "delta_e_from_reference": abs(rng.normal(
            2.0 if label == "NEGATIVE" else 45.0, 4.0
        )),
        "spatial_uniformity": abs(rng.normal(3.5, 1.2)),
        "edge_density": abs(rng.normal(0.05, 0.02)),
        "p05_luminance": float(np.clip(lab_l * 2.0 - 18, 0, 255)),
        "p95_luminance": float(np.clip(lab_l * 2.0 + 18, 0, 255)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=int, default=40,
                        help="Distinct synthetic physical samples.")
    parser.add_argument("--frames-per-sample", type=int, default=3)
    parser.add_argument("--out", default="data/raw/SYNTHETIC_demo.csv",
                        type=Path)
    parser.add_argument("--seed", type=int, default=20260925)
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    rows = []
    for i in range(args.samples):
        label = "POSITIVE" if i % 2 == 0 else "NEGATIVE"
        sample_id = f"SYNTH-{i:04d}"
        for frame in range(args.frames_per_sample):
            rows.append(synthesise(rng, label, sample_id, frame))

    frame = pd.DataFrame(rows)
    missing = [c for c in FEATURE_NAMES if c not in frame.columns]
    if missing:
        raise SystemExit(f"Generator is out of sync with schema: {missing}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(args.out, index=False)

    print(
        f"Wrote {len(frame)} SYNTHETIC rows across {args.samples} synthetic "
        f"samples to {args.out}.\n"
        "REMINDER: this data is generated, not measured. Metrics computed "
        "from it describe the random number generator and nothing else."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
